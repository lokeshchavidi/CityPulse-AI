package com.citypulseai.ai.config;

import org.springframework.boot.context.properties.ConfigurationProperties;

import lombok.Getter;
import lombok.Setter;

@Getter
@Setter
@ConfigurationProperties(prefix = "citypulse.ai")
public class AIProperties {

    /**
     * Enables or disables AI analysis.
     */
    private boolean enabled;

    /**
     * Gemini model to use.
     *
     * Example:
     * gemini-2.5-flash
     */
    private String model;

    /**
     * Controls creativity.
     *
     * Lower values produce more consistent
     * and deterministic responses.
     */
    private Double temperature;

    /**
     * Maximum number of output tokens
     * generated by Gemini.
     */
    private Integer maxOutputTokens;

    /**
     * Minimum confidence score required
     * for AI recommendations.
     */
    private Integer confidenceThreshold;

    /**
     * Number of retry attempts when
     * Gemini temporarily fails.
     */
    private Integer maxRetryAttempts;

}